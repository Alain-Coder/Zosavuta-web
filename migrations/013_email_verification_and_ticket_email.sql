ALTER TABLE users
  ADD COLUMN emailVerified TINYINT(1) NOT NULL DEFAULT 0 AFTER provider;

CREATE TABLE email_verification_tokens (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  uid VARCHAR(128) NOT NULL,
  tokenHash CHAR(64) NOT NULL UNIQUE,
  expiresAt DATETIME NOT NULL,
  consumedAt DATETIME NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_email_verification_uid_created (uid, createdAt),
  INDEX idx_email_verification_expiry (expiresAt),
  FOREIGN KEY (uid) REFERENCES users(uid) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE ticket_email_deliveries (
  orderId VARCHAR(64) NOT NULL PRIMARY KEY,
  status ENUM('PENDING', 'SENDING', 'SENT', 'FAILED') NOT NULL DEFAULT 'PENDING',
  attempts INT NOT NULL DEFAULT 0,
  lastError VARCHAR(1000) NULL,
  sentAt DATETIME NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (orderId) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB;
